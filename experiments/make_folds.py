"""Fixed 6-fold assignment of dataset_v2, grouped by wave realization (seed) — evaluation protocol (a), 27/10/2026.

  python experiments/make_folds.py        # writes data/sim/<DATASET>/folds.csv (default dataset_v2)

Why grouped by seed: a seed is one sea (Hs, Tp, beta, rep) and is replayed for both vessels, the three speeds and both
damping levels (14 runs on average), so runs of one seed must never sit on both sides of a train/test split.
Each (Hs, beta) cell holds 9 seeds (3 Tp x 3 rep); the seeds of a cell are spread over the 6 folds (1 or 2 per fold),
and within that rule every seed goes to the fold with the fewest runs so far, so the folds have about 525 runs each
and every fold contains every Hs, every beta and (through its seeds) every speed, vessel and damping level.
Deterministic: fixed RNG seed, so the file can be regenerated byte for byte.
"""
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIM = os.path.join(ROOT, "data", "sim", os.environ.get("DATASET", "dataset_v2"))
K = 6
RNG_SEED = 20261027


def make_folds(design):
    runs_per_seed = design.groupby("seed").size()
    seeds = design.drop_duplicates("seed")[["seed", "Hs", "Tp", "beta_deg", "rep"]].reset_index(drop=True)
    rng = np.random.default_rng(RNG_SEED)
    fold_runs = np.zeros(K, int)
    fold_of = {}
    for _, cell in seeds.groupby(["Hs", "beta_deg"], sort=True):
        cell = cell.sample(frac=1.0, random_state=int(rng.integers(1 << 31)))
        cell = cell.assign(n=cell.seed.map(runs_per_seed)).sort_values("n", ascending=False, kind="stable")
        in_cell = np.zeros(K, int)
        for s, n in zip(cell.seed, cell.n):
            cap = 1 if in_cell.min() == 0 else 2           # every fold gets one seed of the cell before any gets two
            allowed = np.nonzero(in_cell < cap)[0]
            k = allowed[np.argmin(fold_runs[allowed])]
            fold_of[int(s)] = int(k)
            in_cell[k] += 1
            fold_runs[k] += n
    return design.assign(fold=design.seed.map(fold_of))


if __name__ == "__main__":
    design = pd.read_csv(os.path.join(SIM, "design_matrix.csv"))
    out = make_folds(design)[["id", "name", "seed", "vessel", "Hs", "Tp", "beta_deg", "U", "kappa4", "rep", "dzeta3", "fold"]]
    path = os.path.join(SIM, "folds.csv")
    out.to_csv(path, index=False)
    print(f"wrote {path}")
    print(out.groupby("fold").agg(runs=("id", "size"), seeds=("seed", "nunique")).to_string())
    assert out.groupby("seed").fold.nunique().max() == 1, "a seed spans two folds"
